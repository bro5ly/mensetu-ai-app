-- 質問バンク: 会社に紐づかない、定番の面接質問と「良い回答の型」を保持するグローバルな参照データ。
-- 目的: 企業リサーチの質問生成が会社概要の言い回しだけに引っ張られて過度に狭くなるのを防ぐため、
-- 定番の質問パターンを手本としてLLMプロンプトに渡す(CompanyResearchPromptFactory参照)。
-- WebSearchClientが実プロバイダに接続されるまでは、キュレーションした静的データをここで登録する。

CREATE TABLE question_bank_entries (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    internal_category VARCHAR(50) NOT NULL,
    question_text     TEXT NOT NULL,
    answer_guidance   TEXT NOT NULL,
    created_at        TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_question_bank_category ON question_bank_entries(internal_category);

