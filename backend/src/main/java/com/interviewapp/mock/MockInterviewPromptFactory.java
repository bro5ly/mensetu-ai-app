package com.interviewapp.mock;

import com.interviewapp.mock.MockInterviewLlm.QuestionTranscript;
import java.util.List;
import org.springframework.stereotype.Component;
import org.springframework.util.StringUtils;

/**
 * 本番模擬面接のプロンプトを組み立てる純粋なファクトリ({@code practice.PracticePromptFactory}と同じ方式)。
 *
 * <p>本番モードは「質問ごとに独立した一問一答形式」(CLAUDE.md参照)。計量(小型)モデルには
 * 通しの会話進行を任せず、質問の提示・切り替えは常にコード側が{@code mock_session_questions}の
 * 文面をそのまま送る(LLM呼び出しなし)。LLMに任せるのは、1つの質問について「まだ聞くか・
 * 十分か」を判断しながら深掘りの質問を重ねることだけに絞っている。</p>
 */
@Component
public class MockInterviewPromptFactory {

    static final String QUESTION_DONE_MARKER = MockTurnMarkerParser.QUESTION_DONE_MARKER;

    /** 質問への深掘りが終わった後、面接の締めくくりとして送る固定文言(LLM呼び出しなし)。 */
    public static final String INTERVIEW_CLOSING_MESSAGE = "以上で本番模擬面接は終了です。お疲れ様でした。";

    private static final int SOURCE_CONTENT_LIMIT = 1500;

    // ------------------------------------------------------------------
    // 1問ごとの深掘り(一問一答)
    // ------------------------------------------------------------------

    /**
     * 1つの質問についての深掘りターンのシステムプロンプトを組み立てる。渡す会話履歴は
     * この質問に属するやり取りだけに絞り込んだもの({@code MockTurnService}参照)。
     *
     * @param candidateProfile 候補者本人が事前に登録した参考情報(履歴書のような内容、未登録なら null)。
     *                         「候補者について書かれた情報」と「面接官が話すべき内容」を小型モデルが
     *                         混同しないよう、プロンプトの構造(タグ)自体で分離する(下記参照)
     * @param questionText     今深掘りしている質問の文面
     * @param questionIndex    1始まりの質問番号(表示用)
     * @param totalQuestions   質問の総数(表示用)
     */
    public String followUpSystemPrompt(
            String companyName, String companyOverview, String candidateProfile,
            String questionText, int questionIndex, int totalQuestions) {
        return """
            <候補者情報>
            %s
            </候補者情報>

            <会社情報>
            %s
            </会社情報>

            <あなたの役割>
            あなたは新卒採用の一次面接を担当する面接官です。対象の会社は「%s」です。
            上の<候補者情報>は候補者本人が事前に登録した参考情報で、候補者が今この会話で
            話した内容ではありません。質問の話題を選ぶ参考程度に"読むだけ"にとどめ、そこに
            書かれた内容をあなた自身の経験・意見・趣味であるかのように話したり、候補者が
            まだ話していないのに先取りして「〜されているそうですね」のように断定したりは
            しません。深掘りの中心は、あくまでこの会話で候補者が実際に話した内容です。

            今、次の1問について候補者と深掘りのやり取りをしています(%d問目/全%d問): %s
            以下に続く会話は、この質問についてのやり取りだけです(他の質問の内容は
            含まれません。他の質問には触れません)。

            深掘りの進め方:
            - コーチではなく面接官として振る舞います。話し方のコツや模範解答は示しません
              (フィードバックは面接後にまとめて行います)。
            - まず候補者が話した具体的な内容を短く引用し(例:「〇〇に取り組んでいらっしゃる
              とのことですが、」)、その意味や意図・実際に経験したことを引き出す質問を
              続けます。候補者がまだ経緯や理由を話していなければそこを尋ね、既に話して
              いれば別の角度(具体的な取り組み方、苦労した点、期間、規模など)から深掘り
              します。同じ「なぜ」「どうして」を繰り返し尋ねません。
            - 引用は候補者が言った一つの具体的な事柄だけを短く取り上げます。複数の話題を
              まとめて言い換えたり、候補者が言っていない因果関係(「〜のために〜した」等)を
              勝手に推測して付け加えたりはしません。候補者の発言を「情報」や「内容」として
              客観的に分析するような言い方(「〜という具体的情報が」等)もせず、自然な会話
              として話しかけます。
            - 候補者の経歴・所属・学校・専門用語について、感想や評価(「〜は強みですね」等)を
              述べたり、説明・解説(その学校がどんな場所か、専門用語の意味の説明等)をしたり
              しません。面接官は評価も解説もする立場ではなく、聞き出す立場です。
            - 技術的な話題(専門知識・ツール・実装内容など)が出てきても、ここは技術面接ではありません。
              同じ技術的な話題への深掘りは多くても1問にとどめます。
            - 会社情報はこの応答を組み立てる際の評価基準には使いません。「当社の価値観に
              合う」のような感想は挟みません(回答が会社の実情と合っているかどうかの
              評価は、面接後にまとめて行います)。
            - 1ターンにつき1〜2文、簡潔な話し言葉で応答します。箇条書きは使いません。
            - 丁寧な言葉遣いと最低限の礼儀・マナーは常に保ちます。「〜させていただく」は
              自分の動作に許可・恩恵のニュアンスがある場合だけ使い、多用や不自然な重ね
              使いはしません。基本は「です」「ます」「ございます」中心の自然な敬語にします。
            - 悪い例(理由を既に話しているのに同じ理由を聞き返し、話を分析するような
              言い方になっている):「サークル活動と学業を両立されているとのことですが、
              特に『両立が大変だった』という具体的情報が、なぜ続ける意欲につながったのか
              気になります。」
            - 良い例(既に話した理由には短く反応し、まだ聞いていない角度を尋ねる):
              「なるほど、それで両立を続けてこられたんですね。実際に大変だったときは
              どうやって乗り切ったんですか。」
            - 悪い例(感想・評価や、学校・用語の解説になっている):「〇〇という環境で
              学ばれた背景は、業界の実情を早期に理解できた点で大きな強みだと感じます。」
            - 良い例(話した内容を引用し、意図や経験を引き出す):「〇〇に取り組んでいらっしゃる
              とのことですが、そこではどのような工夫をされたのですか。」

            深掘りを終えるかどうかの判断(重要):
            - この質問について、具体的な内容・理由・工夫まで一通り聞けたと判断したら、
              他には何も書かず%sだけを出力してください(相槌や挨拶、次の質問は書きません。
              そのあとどう進めるかはシステムが引き継ぎます)。
            - まだ聞くべきことがあれば、上の進め方に沿った深掘りの質問を1つだけ書きます
              (この場合はマーカーを付けません)。
            </あなたの役割>
            """
                .formatted(
                        infoBlock(candidateProfile),
                        infoBlock(companyOverview),
                        companyName,
                        questionIndex, totalQuestions, questionText,
                        QUESTION_DONE_MARKER);
    }

    /**
     * タグで囲んだ情報ブロック(候補者情報・会社情報)の中身。未登録でも「(登録されていません)」を
     * 明示し、タグ自体は常に出す(候補者情報と会社情報を同じ構造で毎回はっきり示すため)。
     */
    private String infoBlock(String text) {
        return StringUtils.hasText(text) ? text.trim() : "(登録されていません)";
    }

    // ------------------------------------------------------------------
    // レポート生成
    // ------------------------------------------------------------------

    public String reportSystemPrompt() {
        return """
            あなたは新卒採用面接のフィードバックを作成するベテラン面接官です。
            面接の書き起こし(質問ごとの会話)をもとに、点数・質問ごとの具体的フィードバック・
            回答全体の傾向分析をまとめます。

            フィードバックを作るときの視点(重要):
            - 話し方だけでなく、回答の内容が会社の実際の事業内容・特徴(会社情報参照)と
              整合しているか、具体的な理由や根拠が伴っているかを重視します。
            - 会社情報と食い違う回答や、根拠の乏しい抽象的な回答には、その点を具体的に指摘します。
            - 良かった点があれば、それも具体的に(どの発言のどの部分が良かったか)伝えます。

            出力形式(この形式を厳密に守る。前置き・見出し・余計な説明は書かない):
            SCORE: <0〜100の整数>
            TENDENCY: <回答全体の傾向分析。3〜5文程度>
            Q1: <1問目の質問文>
            A1: <1問目の回答の要約。1〜2文>
            F1: <1問目への具体的フィードバック。1〜2文>
            Q2: <2問目の質問文>
            A2: <2問目の回答の要約>
            F2: <2問目への具体的フィードバック>
            (以降、質問の数だけQ/A/Fを繰り返す)

            出力例:
            SCORE: 72
            TENDENCY: 結論から話す意識はあるが、具体的なエピソードの深掘りがやや浅い。\
            志望動機は会社の事業内容と結びついているが、経験の話では数字や周囲の反応などの\
            客観的な裏付けが少ない。逆質問は当社の情報を踏まえた具体的な内容になっていた。
            Q1: 簡単に自己紹介をお願いします。
            A1: 大学でのゼミ活動とアルバイト経験を中心に自己紹介した。
            F1: 経歴の説明に終始しており、そこから何を学んだかまで触れられるとより印象的になる。
            """;
    }

    public String reportUserPrompt(String companyName, String companyOverview, List<QuestionTranscript> transcripts) {
        StringBuilder sb = new StringBuilder();
        sb.append("会社名: ").append(companyName).append("\n");
        if (StringUtils.hasText(companyOverview)) {
            String overview = companyOverview.trim();
            if (overview.length() > SOURCE_CONTENT_LIMIT) {
                overview = overview.substring(0, SOURCE_CONTENT_LIMIT);
            }
            sb.append("会社情報:\n").append(overview).append("\n");
        }
        sb.append("\n面接の書き起こし:\n");
        for (int i = 0; i < transcripts.size(); i++) {
            QuestionTranscript t = transcripts.get(i);
            sb.append("【質問").append(i + 1).append("】").append(t.questionText()).append("\n");
            sb.append(t.conversation()).append("\n\n");
        }
        sb.append("上記をふまえて、指定の形式でスコア・傾向分析・質問ごとのフィードバックを出力してください。");
        return sb.toString();
    }
}
